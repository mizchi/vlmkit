export const GLYPH_WIDTH = 5;
export const GLYPH_HEIGHT = 7;
/** One blank column between glyphs, so an advance is 6 columns at scale 1. */
const ADVANCE = GLYPH_WIDTH + 1;

/** Target of a draw: any RGBA buffer that knows its own dimensions. */
export interface RgbaTarget {
  width: number;
  height: number;
  data: Uint8Array;
}

/** Height in px of one line at `scale`. */
export function textHeight(scale = 1): number {
  return GLYPH_HEIGHT * scale;
}

/** Width in px of `text` at `scale`, excluding the trailing blank column. */
export function measureText(text: string, scale = 1): number {
  const drawable = [...text].filter((ch) => ch in GLYPHS).length;
  if (drawable === 0) return 0;
  return (drawable * ADVANCE - 1) * scale;
}

/**
 * The longest prefix of `text` that fits in `maxWidth`, with a trailing `..` when
 * something was dropped.
 *
 * Truncation is at the *end* deliberately, even though the distinguishing part of a
 * CSS selector is usually its tail: a label whose head is cut cannot be matched back
 * to the terminal output at all, while one whose tail is cut still can.
 */
export function fitText(text: string, maxWidth: number, scale = 1): string {
  if (measureText(text, scale) <= maxWidth) return text;
  const ellipsis = "..";
  const room = maxWidth - measureText(ellipsis, scale);
  if (room <= 0) return "";
  let out = "";
  for (const ch of text) {
    if (measureText(out + ch, scale) > room) break;
    out += ch;
  }
  return out + ellipsis;
}

/**
 * Draw `text` into an RGBA buffer with its top-left at (x, y). Writes fully opaque
 * ink; pixels outside the buffer are skipped rather than wrapped.
 */
export function drawText(
  target: RgbaTarget,
  text: string,
  x: number,
  y: number,
  rgb: readonly [number, number, number],
  scale = 1,
): void {
  let cursor = x;
  for (const ch of text) {
    const glyph = GLYPHS[ch];
    if (!glyph) continue;
    for (let row = 0; row < GLYPH_HEIGHT; row++) {
      const bits = glyph[row]!;
      for (let col = 0; col < GLYPH_WIDTH; col++) {
        if (bits[col] !== "1") continue;
        for (let dy = 0; dy < scale; dy++) {
          const py = y + row * scale + dy;
          if (py < 0 || py >= target.height) continue;
          for (let dx = 0; dx < scale; dx++) {
            const px = cursor + col * scale + dx;
            if (px < 0 || px >= target.width) continue;
            const i = (py * target.width + px) * 4;
            target.data[i] = rgb[0];
            target.data[i + 1] = rgb[1];
            target.data[i + 2] = rgb[2];
            target.data[i + 3] = 255;
          }
        }
      }
    }
    cursor += ADVANCE * scale;
  }
}
